
# Step 1: Store the values
mean1 = 38
wrong_number = 36
correct_number = 56
total_number = 40

# Step 2: Calculate the original sum
sum = mean1 * total_number
print("Original sum:", sum)

# Step 3: Correct the sum
num2 = sum - (wrong_number - correct_number)
print("Corrected sum:", num2)

# Step 4: Calculate the corrected mean
mean2 = num2 / total_number
print("Corrected mean:", mean2)
